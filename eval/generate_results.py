"""Assembles eval/results.md from the markdown fragments each eval script
wrote to eval/.cache/section_*.md, plus a header (date, git sha, commands)
and a Limitations section. Run AFTER run_compliance_eval.py,
retrieval_eval.py, and faithfulness_eval.py -- this script does not run
any eval itself, it only assembles their already-written output so the
final doc is never out of sync with what was actually measured.
"""

import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))

import eval_common  # noqa: E402

OUT_PATH = os.path.join(os.path.dirname(__file__), "results.md")

SECTIONS = ["compliance", "retrieval", "faithfulness"]

COMMANDS = [
    "python eval/build_compliance_set.py",
    "python eval/run_compliance_eval.py            # offline; add --live to call the real judge (capped, cached)",
    "python eval/retrieval_eval.py",
    "python eval/faithfulness_eval.py",
    "python eval/check_thresholds.py",
    "python eval/generate_results.py",
]

LIMITATIONS = """## Limitations -- what these numbers do NOT show

- **Small sets.** 62 compliance cases, 24 retrieval documents across 4
  themes, 8 faithfulness samples / 14 claims. None of these are large
  enough to produce statistically tight estimates -- a single flipped
  label can move a percentage by several points. Treat every number above
  as directional, not a precise population estimate.
- **Synthetic, single-annotator data.** Every case/sample was written and
  labeled by the engineer who also wrote the detectors being evaluated
  (see `eval/LABELING_GUIDE.md`'s own caveat). This is NOT real client
  briefing data, and the adversarial cases were written with knowledge of
  the exact regexes they're trying to evade -- a real adversary without
  that knowledge, or a real compliance reviewer with professional
  training, would likely produce different numbers in both directions.
- **The retrieval eval uses a hashed-bag-of-words embedding stub**, not the
  real HuggingFace `bge-small-en-v1.5` model `backend/llm_client.py` calls
  in production. It is deterministic and gives *some* real signal (shared
  vocabulary clusters closer), but its absolute recall@k/MRR numbers are a
  floor on a weak proxy, not a prediction of the real model's retrieval
  quality. The distance-threshold *sweep methodology* generalizes; the
  specific recommended threshold value in the stub's embedding space does
  not transfer directly to the real 384-dim embedding space.
- **The faithfulness eval's claim-support check is a lexical-overlap
  fallback** (Jaccard word-set similarity), not an LLM judge -- it will
  miss paraphrased grounding (a claim that's genuinely supported but uses
  different words than the source) and will not catch subtler
  misattributions that happen to share vocabulary with an unrelated chunk.
  An `--live` LLM-judge mode for this check was not implemented this
  phase; see Handoff notes below.
- **Judge-only and combined compliance metrics are unmeasured this
  phase** (see the compliance section above) -- the rules-only numbers are
  real; the other two systems' numbers are explicitly marked
  `[MEASURE: run `make eval-live`]` rather than estimated or guessed.
- **No live LLM/Tavily/HF/Groq API calls were made to produce any number
  in this document.** Every number here came from a command in the list
  above, run against purely local/offline code paths (`rules.py`'s regex
  engine, the embedding stub, hand-built fixtures). This is intentional --
  see the HARD SAFETY RULES in `claude_code_master_prompt.md` and
  `docs/PROGRESS.md`'s live-call-budget notes.
"""


def main():
    date = datetime.date.today().isoformat()
    sha = eval_common.git_sha()

    missing = [s for s in SECTIONS if not os.path.exists(os.path.join(eval_common.CACHE_DIR, f"section_{s}.md"))]
    if missing:
        print(f"Missing section(s): {missing} -- run their eval script(s) first.")
        sys.exit(1)

    parts = []
    parts.append("# Evaluation results\n")
    parts.append(f"Generated: {date} | git sha: `{sha}`\n")
    parts.append("Auto-generated by `eval/generate_results.py` from the markdown fragments each eval script "
                  "writes to `eval/.cache/`. Do not hand-edit this file -- re-run the eval scripts and "
                  "`generate_results.py` instead, so it can never drift from a command that was actually run.\n")
    parts.append("## Commands run\n")
    parts.append("```\n" + "\n".join(COMMANDS) + "\n```\n")

    for s in SECTIONS:
        with open(os.path.join(eval_common.CACHE_DIR, f"section_{s}.md"), encoding="utf-8") as f:
            parts.append(f.read())

    parts.append(LIMITATIONS)

    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))

    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
